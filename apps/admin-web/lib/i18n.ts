export function t(lang: Lang, key: CopyKey): string {
  return strings[lang][key];
}

export function statusLabel(lang: Lang, status: string): string {
  const map: Record<string, CopyKey> = {
    Submitted: 'submitted',
    Assigned: 'assigned',
    InProgress: 'inProgress',
    WaitingCustomer: 'waitingCustomer',
    Completed: 'completed',
    Cancelled: 'cancelled',
  };
  const k = map[status];
  return k ? t(lang, k) : status;
}

export function bugReportStatusLabel(lang: Lang, status: string): string {
  const map: Record<string, CopyKey> = {
    open: 'bugStatusOpen',
    in_progress: 'bugStatusInProgress',
    resolved: 'bugStatusResolved',
    dismissed: 'bugStatusDismissed',
  };
  const k = map[status];
  return k ? t(lang, k) : status;
}

export function miniAppStatusLabel(lang: Lang, status: string): string {
  switch (status) {
    case 'pending':
      return t(lang, 'miniAppsStatusPending');
    case 'approved':
      return t(lang, 'miniAppsStatusApproved');
    case 'rejected':
      return t(lang, 'miniAppsStatusRejected');
    case 'disabled':
      return t(lang, 'miniAppsStatusDisabled');
    default:
      return status;
  }
}
