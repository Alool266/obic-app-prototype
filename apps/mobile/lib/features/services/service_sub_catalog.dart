class ObicSubService {
  const ObicSubService({
    required this.id,
    required this.parentSlug,
    required this.icon,
    required this.nameAr,
    required this.nameEn,
    required this.descAr,
    required this.descEn,
    required this.priceAr,
    required this.priceEn,
    this.sortOrder = 0,
    this.nameZh = '',
    this.descZh = '',
    this.priceZh = '',
  });

  final String id;
  final String parentSlug;
  final String icon;
  final int sortOrder;
  final String nameAr;
  final String nameEn;
  final String nameZh;
  final String descAr;
  final String descEn;
  final String descZh;
  final String priceAr;
  final String priceEn;
  final String priceZh;

  String name(String langCode) {
    switch (langCode) {
      case 'ar':
        return nameAr;
      case 'zh':
        return nameZh.isNotEmpty ? nameZh : nameEn;
      default:
        return nameEn;
    }
  }

  String desc(String langCode) {
    switch (langCode) {
      case 'ar':
        return descAr;
      case 'zh':
        return descZh.isNotEmpty ? descZh : descEn;
      default:
        return descEn;
    }
  }

  String price(String langCode) {
    switch (langCode) {
      case 'ar':
        return priceAr;
      case 'zh':
        return priceZh.isNotEmpty ? priceZh : priceEn;
      default:
        return priceEn;
    }
  }

  factory ObicSubService.fromJson(Map<String, dynamic> json) {
    return ObicSubService(
      id: json['id'] as String,
      parentSlug: json['parentSlug'] as String,
      icon: json['icon'] as String,
      sortOrder: json['sortOrder'] as int? ?? 0,
      nameAr: json['nameAr'] as String,
      nameEn: json['nameEn'] as String,
      nameZh: json['nameZh'] as String? ?? '',
      descAr: json['descAr'] as String,
      descEn: json['descEn'] as String,
      descZh: json['descZh'] as String? ?? '',
      priceAr: json['priceAr'] as String,
      priceEn: json['priceEn'] as String,
      priceZh: json['priceZh'] as String? ?? '',
    );
  }
}

