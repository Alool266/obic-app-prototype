/// Simple offline country filter (healthcare parent is CN-only in API seed).
List<Map<String, Object?>> filterMegaCatalogJson(String? countryCode) {
  if (countryCode == null || countryCode.isEmpty) return kMegaCatalogJson;
  final c = countryCode.toUpperCase();
  return kMegaCatalogJson.where((m) {
    final slug = m['slug'] as String?;
    if (slug == 'healthcare' && c != 'CN') return false;
    return true;
  }).toList();
}
